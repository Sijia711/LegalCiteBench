"""
Create Category 4-2 fake case verification questions.

This is Step 2 of Cat4-2 construction.

Input:
  Cat4-2 true verification files from Step 1.

Output:
  Cat4-2 fake verification files. Each fake example is created by replacing the
  true case reference in the final "Can I reference ..." question with a random
  different case from the same source file.

The ground truth remains the original correct case.

Example:
python data/cat4/cat4_2_step2_create_wrong_cases.py \
  --input_files \
    data/cat4/cat4-2/step1/cat4-2_true_openai_gpt-4o-mini.jsonl \
    data/cat4/cat4-2/step1/cat4-2_true_google_gemini-2.5-flash.jsonl \
    data/cat4/cat4-2/step1/cat4-2_true_anthropic_claude-3.5-haiku.jsonl \
  --output_dir data/cat4/cat4-2/step2 \
  --seed 42
"""

import argparse
import json
import random
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from tqdm import tqdm


def load_jsonl(path: Path) -> List[Dict[str, Any]]:
    records = []

    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                records.append(json.loads(line))

    return records


def append_jsonl(path: Path, records: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "a", encoding="utf-8") as f:
        for record in records:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
        f.flush()


def load_processed_keys(output_file: Path) -> set:
    if not output_file.exists():
        return set()

    processed = set()

    with open(output_file, "r", encoding="utf-8") as f:
        for line in f:
            try:
                data = json.loads(line)
                key = f"{data.get('source_case_id', data.get('id', ''))}||{data.get('legal_angle', '')}"
                processed.add(key)
            except Exception:
                pass

    return processed


def extract_case_reference_from_question(
    question: str,
    ground_truth: Dict[str, Any],
) -> Optional[str]:
    """
    Extract the case reference used after "Can I reference ... for".

    This preserves the exact format generated by the LLM.
    """
    case_name = ground_truth.get("case_name", "")
    case_cite = ground_truth.get("case_cite", "")
    decision_date = ground_truth.get("decision_date", "")
    year = decision_date.split("-")[0] if decision_date else ""

    can_i_match = re.search(r"Can I reference\s+(.+?)\s+for", question, re.IGNORECASE | re.DOTALL)

    if can_i_match:
        reference_text = can_i_match.group(1).strip()

        if case_cite and case_cite in reference_text:
            return reference_text

    if case_cite and case_cite not in question:
        return None

    candidates = []

    if case_name and case_cite and year:
        candidates.append(f"{case_name}, {case_cite} ({year})")
        candidates.append(f"*{case_name}*, {case_cite} ({year})")

    if case_name and case_cite:
        candidates.append(f"{case_name}, {case_cite}")
        candidates.append(f"*{case_name}*, {case_cite}")

    for candidate in candidates:
        if candidate in question:
            return candidate

    if case_cite:
        pattern_with_year = rf"([^.!?\n]+?),\s*{re.escape(case_cite)}\s*\((\d{{4}})\)"
        match = re.search(pattern_with_year, question)
        if match:
            return match.group(0)

        pattern_no_year = rf"([^.!?\n]+?),\s*{re.escape(case_cite)}"
        match = re.search(pattern_no_year, question)
        if match:
            return match.group(0)

    return None


def make_case_reference_like_original(
    original_case_ref: str,
    wrong_case: Dict[str, Any],
) -> str:
    """
    Build the wrong case reference using a similar format to the original.
    """
    wrong_case_name = wrong_case.get("case_name", "")
    wrong_case_cite = wrong_case.get("case_cite", "")
    wrong_decision_date = wrong_case.get("decision_date", "")
    wrong_year = wrong_decision_date.split("-")[0] if wrong_decision_date else ""

    uses_italic = original_case_ref.strip().startswith("*")
    has_year = bool(re.search(r"\(\d{4}\)", original_case_ref))

    if uses_italic:
        if has_year and wrong_year:
            return f"*{wrong_case_name}*, {wrong_case_cite} ({wrong_year})"
        return f"*{wrong_case_name}*, {wrong_case_cite}"

    if has_year and wrong_year:
        return f"{wrong_case_name}, {wrong_case_cite} ({wrong_year})"

    return f"{wrong_case_name}, {wrong_case_cite}"


def load_all_cases_from_true_qas(true_qas: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """
    Load unique cases from true QA ground_truth fields.
    """
    cases = {}

    for qa in true_qas:
        case_id = str(qa.get("source_case_id", qa.get("id", "")))

        if case_id and case_id not in cases:
            cases[case_id] = qa.get("ground_truth", {})

    return cases


def create_wrong_case_qa(
    original_qa: Dict[str, Any],
    wrong_case: Dict[str, Any],
) -> Optional[Dict[str, Any]]:
    source_id = str(original_qa.get("source_case_id", original_qa.get("id", "")))
    original_question = original_qa["question"]

    original_case_ref = extract_case_reference_from_question(
        question=original_question,
        ground_truth=original_qa["ground_truth"],
    )

    if original_case_ref is None:
        return None

    wrong_case_ref = make_case_reference_like_original(
        original_case_ref=original_case_ref,
        wrong_case=wrong_case,
    )

    wrong_question = original_question.replace(original_case_ref, wrong_case_ref, 1)

    if wrong_question == original_question:
        return None

    return {
        "id": source_id,
        "source_case_id": source_id,
        "qa_style": "4-2-fake",
        "legal_angle": original_qa["legal_angle"],
        "question": wrong_question,
        "ground_truth": original_qa["ground_truth"],
        "wrong_case_cited": wrong_case,
        "model": original_qa["model"],
    }


def infer_output_name(input_file: Path) -> str:
    stem = input_file.stem

    if stem.startswith("cat4-2_true_"):
        suffix = stem.replace("cat4-2_true_", "", 1)
    elif stem.startswith("4-2-1_"):
        suffix = stem.replace("4-2-1_", "", 1)
    else:
        suffix = stem

    return f"cat4-2_fake_{suffix}.jsonl"


def process_file(
    input_file: Path,
    output_dir: Path,
    rng: random.Random,
) -> Dict[str, int]:
    print("\n" + "=" * 60)
    print(f"Processing: {input_file}")
    print("=" * 60)

    true_qas = load_jsonl(input_file)
    print(f"Loaded true QAs: {len(true_qas)}")

    case_dict = load_all_cases_from_true_qas(true_qas)
    print(f"Extracted unique cases: {len(case_dict)}")

    output_file = output_dir / infer_output_name(input_file)
    processed_keys = load_processed_keys(output_file)

    to_process = [
        qa for qa in true_qas
        if f"{qa.get('source_case_id', qa.get('id', ''))}||{qa.get('legal_angle', '')}" not in processed_keys
    ]

    print(f"Already processed: {len(true_qas) - len(to_process)}")
    print(f"To process: {len(to_process)}")
    print(f"Output file: {output_file}")

    stats = {
        "total": len(true_qas),
        "generated": 0,
        "replacement_failed": 0,
        "no_available_wrong_case": 0,
    }

    buffer = []

    for qa in tqdm(to_process, desc=f"Cat4-2 fake - {input_file.stem}"):
        source_id = str(qa.get("source_case_id", qa.get("id", "")))

        available_case_ids = [
            case_id for case_id in case_dict.keys()
            if case_id != source_id
        ]

        if not available_case_ids:
            stats["no_available_wrong_case"] += 1
            continue

        wrong_case_id = rng.choice(available_case_ids)
        wrong_case = case_dict[wrong_case_id]

        wrong_qa = create_wrong_case_qa(qa, wrong_case)

        if wrong_qa is None:
            stats["replacement_failed"] += 1
            continue

        buffer.append(wrong_qa)
        stats["generated"] += 1

        if len(buffer) >= 100:
            append_jsonl(output_file, buffer)
            buffer = []

    if buffer:
        append_jsonl(output_file, buffer)

    print(f"Generated: {stats['generated']}")
    print(f"Replacement failed: {stats['replacement_failed']}")
    print(f"No available wrong case: {stats['no_available_wrong_case']}")
    print(f"Saved to: {output_file}")

    return stats


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create Cat4-2 fake case verification examples."
    )

    parser.add_argument("--input_files", nargs="+", required=True)
    parser.add_argument("--output_dir", type=str, required=True)
    parser.add_argument("--seed", type=int, default=42)

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    rng = random.Random(args.seed)

    print("=" * 60)
    print("Category 4-2 Step 2: Create Fake Verification Questions")
    print(f"Output directory: {output_dir}")
    print(f"Seed: {args.seed}")
    print("=" * 60)

    total_stats = {
        "total": 0,
        "generated": 0,
        "replacement_failed": 0,
        "no_available_wrong_case": 0,
    }

    for input_path in args.input_files:
        stats = process_file(
            input_file=Path(input_path),
            output_dir=output_dir,
            rng=rng,
        )

        for key in total_stats:
            total_stats[key] += stats.get(key, 0)

    print("\n" + "=" * 60)
    print("OVERALL SUMMARY")
    print("=" * 60)
    for key, value in total_stats.items():
        print(f"{key}: {value}")
    print("=" * 60)


if __name__ == "__main__":
    main()